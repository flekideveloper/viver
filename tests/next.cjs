/* Real browser-side VIVER Next integration test; no live API calls. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {JSDOM,VirtualConsole}=require('jsdom');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
(async()=>{
 const errors=[],vcon=new VirtualConsole();
 vcon.on('jsdomError',e=>{if(!String(e).includes('Not implemented'))errors.push(String(e))});
 const dom=new JSDOM(read('index.html'),{url:'https://flekideveloper.github.io/viver/',runScripts:'outside-only',pretendToBeVisual:true,virtualConsole:vcon});
 const w=dom.window,$=q=>w.document.querySelector(q);
 w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};w.confirm=()=>true;
 vm.runInContext(read('app.js'),dom.getInternalVMContext(),{filename:'app.js'});
 w.VIVERConnections={getActiveYoutubeChannel:()=>'',getConnections:()=>[],getStatus:()=> 'ready',request:async()=>{throw Error('not connected')}};
 let cloudWrite=null;const username='viver_tester',user={id:'TEST_ACCOUNT_ID',username};
 const ok=(data,status=200)=>({ok:status<400,status,json:async()=>data});
 w.fetch=async (url,opt={})=>{
  const u=new URL(url),method=opt.method||'GET';
  if(u.pathname==='/v1/auth/register'&&method==='POST')return ok({user,token:'T'.repeat(43),recovery:'R'.repeat(43)},201);
  if(u.pathname==='/v1/auth/me')return ok({user});
  if(u.pathname==='/v1/teams'&&method==='GET')return ok({teams:[]});
  if(u.pathname==='/v1/workspace'&&method==='GET')return ok({exists:false,version:0});
  if(u.pathname==='/v1/workspace'&&method==='PUT'){cloudWrite=JSON.parse(opt.body);return ok({ok:true,version:1,updatedAt:Date.now()})}
  throw Error('unexpected API '+method+' '+u.pathname);
 };
 vm.runInContext(read('viver-space.js'),dom.getInternalVMContext(),{filename:'viver-space.js'});
 vm.runInContext(read('viver-tools.js'),dom.getInternalVMContext(),{filename:'viver-tools.js'});
 assert($('#viver-id-card'),'ID UI mounted inside Settings');
 assert($('#page-teams'),'Teams page present');
 assert($('[data-page="teams"]'),'Teams navigation present');
 assert($('#vs-studio-plus'),'Studio 2.0 mounted');
 assert($('#vs-smart-notices'),'smart alerts mounted');
 assert($('#vs-advanced-insights'),'real analytics module mounted');
 $('#viver-id-card [data-vs-mode="register"]').click();
 assert($('#vs-auth-form'),'register form visible');
 $('#vs-auth-form [name="username"]').value=username;
 assert.equal($('#vs-auth-form [name="password"]').minLength,6,'registration minimum is six characters');
 assert($('#vs-auth-form').textContent.includes('4 літери'),'password requirements are visible');
 $('#vs-auth-form [name="password"]').value='abcd1!';
 $('#vs-auth-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 await new Promise(r=>setTimeout(r,30));
 assert.equal(w.VIVERId.getUser()?.username,username,'registration stored session in UI');
 assert($('#vs-recovery-value')?.textContent==='R'.repeat(43),'key displayed only after registration');
 assert.equal(w.localStorage.getItem('viver-id-session-v1'),'T'.repeat(43),'session persists');
 const p={id:'p1',title:'Test production',date:'2026-12-02T18:00',platform:'youtube',status:'idea',notes:'',checks:[],created:Date.now()};
 w.VIVERCore.state.plans.push(p);
 w.dispatchEvent(new w.Event('viver-studio-updated'));
 const select=$('#vs-studio-select');assert(select,'existing plan shown in Studio');
 const script=$('#vs-studio-form [name="script"]');script.value='Hook, story, CTA';
 $('#vs-studio-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
 assert.equal(JSON.parse(w.localStorage.getItem('viver-studio-v2')).p1.script,'Hook, story, CTA','script saved locally');
 $('#vs-studio-plus [data-vs-studio-template="youtube"]').click();
 assert(p.checks.length>=5,'template inserts actionable production checks');
 $('#viver-id-card [data-vs-action="save"]').click();
 await new Promise(r=>setTimeout(r,30));
 assert.equal(cloudWrite?.version,0);
 assert.equal(cloudWrite?.workspace?.studio?.includes('Hook, story, CTA'),true,'cloud saves actual Studio script');
 assert.equal(cloudWrite.workspace.workspace.plans[0].title,'Test production','cloud includes actual plan');
 assert.equal(JSON.stringify(cloudWrite).includes('viver-connect-key-v1'),false,'no OAuth local capability uploaded');
 const r={id:'r1',title:'Due task',due:new Date(Date.now()-60000).toISOString(),done:false};
 w.VIVERCore.state.reminders.push(r);
 $('#vs-smart-notices [data-vs-alerts="scan"]').click();
 assert($('#vs-smart-notices').textContent.includes('Due task'),'due reminder detected');
 w.VIVERCore.nav('teams');
 assert($('#page-teams').classList.contains('active'),'Teams accessible by app navigation');
 assert($('#vs-create-team'),'logged-in account can create a team');
 assert.equal(errors.length,0,'no unexpected browser errors: '+errors.join(', '));
 dom.window.close();
 console.log('VIVER Next browser tests: PASS — ID, recovery display, cloud backup, studio, alerts, Teams, navigation');
})().catch(e=>{console.error(e);process.exit(1)});
